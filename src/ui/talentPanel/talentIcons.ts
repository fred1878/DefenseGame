const ICON_PX = 48;

export function talentIconKey(name: string): string {
  return `talent_icon_${ICON_SVG[name] ? name : "star"}`;
}

function svgDataUri(body: string, color: string): string {
  const svg = `<svg width="${ICON_PX}" height="${ICON_PX}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" xmlns="http://www.w3.org/2000/svg">${body}</svg>`;
  return `data:image/svg+xml;base64,${btoa(svg)}`;
}

/** Queue every icon texture (parchment stroke) that is not loaded yet. */
export function ensureTalentIcons(scene: Phaser.Scene): void {
  for (const [name, body] of Object.entries(ICON_SVG)) {
    const key = talentIconKey(name);
    if (scene.textures.exists(key)) continue;
    scene.textures.addBase64(key, svgDataUri(body, "#E9DFCB"));
  }
}
